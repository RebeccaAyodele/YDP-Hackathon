import json
from dataclasses import dataclass
from pathlib import Path


@dataclass
class LGAContext:
    lga_id: str
    lga_name: str
    state: str
    geopolitical_zone: str
    centroid_lat: float
    centroid_lon: float
    rurality_rate: float  # Proportion of rural population (0.0 to 1.0)
    poverty_headcount_mpi: float  # Multidimensional Poverty Index (MPI) score (0.0 to 1.0; State range: 0.026 - 0.562)
    full_immunization_rate: float  # NDHS Full Immunization Coverage % (0.0 to 1.0)
    anc4_coverage_rate: float  # NDHS ANC 4+ visits % (0.0 to 1.0)
    under5_mortality_per_1k: float  # NDHS U5 mortality per 1,000 live births
    malaria_endemicity_score: float  # WHO malaria burden score (0.0 to 1.0)
    cholera_risk_score: float  # Water-borne / cholera risk index (0.0 to 1.0)
    road_access_index: float  # Logistics / transport accessibility (0.0=remote/poor, 1.0=metropolitan highway)
    telecom_coverage_rate: float  # Mobile/GSM reporting connectivity (0.0 to 1.0)


